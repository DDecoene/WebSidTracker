// export.js - assembler text (ACME syntax), the ready-to-run .prg, the .sid file, and the project file (JSON).
//
// The assembler text has exactly the layout of serialise.js, so a song file assembled
// at some address gives the same bytes as serialiseSong(song, thatAddress).
//
// Part of the WebSidTracker web app, GPL version 3 or later (see ../LICENSE).

import { INSTRUMENT_TABLES, serialiseEffects, serialiseInstruments, serialiseSong } from './serialise.js';
import { LIMITS, defaultInstrument, noteName, validate } from './project.js';
import { FORMAT, RELEASE } from '../version.js';
import { NewerFormatError, OlderFormatError, readFormat } from './format.js';

const hex2 = (v) => '$' + v.toString(16).toUpperCase().padStart(2, '0');
const signed = (v) => (v < 0 ? String(v) : '+' + v);

// Chunks an array into lines of `size` values.
function chunks(values, size) {
  const out = [];
  for (let i = 0; i < values.length; i += size) out.push(values.slice(i, i + size));
  return out;
}

/** The comment line that tells which format and release wrote an exported assembler file. */
export function versionLine(format = FORMAT, release = RELEASE) {
  return `; websidtracker format ${format}, release ${release}`;
}

// ---------------------------------------------------------------- instruments

const TABLE_HELP = {
  inst_wave: 'control register without the gate bit (waveform in bits 7-4)',
  inst_ad: 'attack / decay',
  inst_sr: 'sustain / release',
  inst_pw_lo: 'start pulse width, low byte',
  inst_pw_hi: 'start pulse width, high nibble',
  inst_pw_step: 'pulse sweep per frame (signed)',
  inst_pw_min: 'sweep lower limit, pulse width / 16',
  inst_pw_max: 'sweep upper limit, pulse width / 16',
  inst_vib_delay: 'frames before the vibrato starts',
  inst_vib_depth: 'vibrato width, 1/16 of the distance to the next semitone',
  inst_vib_speed: 'frames per half vibrato period',
  inst_arp: 'arpeggio: first offset in semitones (signed)',
  inst_drum_noise: 'drum: frames of noise at the start (0 = not a drum)',
  inst_drum_fall: 'drum: frequency units the tone falls per frame',
  inst_release: 'frames at the end of a note kept for the clean restart',
  inst_arp2: 'arpeggio: second offset in semitones (signed, 0 = a two-note arpeggio)',
  inst_slide: 'pitch slide: frequency change per frame in units of 8 (signed, 0 = no slide)',
};

// Number of table entries to export: highest defined instrument + 1 (at least 1).
function usedInstruments(instruments) {
  return Math.max(1, instruments.reduce((top, inst, n) => (inst ? n + 1 : top), 0));
}

export function exportInstrumentsAsm(instruments) {
  const count = usedInstruments(instruments);
  const tables = serialiseInstruments(instruments);
  const lines = [
    '; instruments.asm - generated by WebSidTracker. Edit the instruments in the tracker, not here.',
    versionLine(),
    '; One table per field, indexed by the instrument number (see docs/design-player-format-and-timing.md, section 5).',
    ';',
    '; Instruments in this file:',
  ];
  for (let n = 0; n < count; n++) lines.push(`;   ${hex2(n)}  ${instruments[n] ? instruments[n].name : '(unused)'}`);
  for (const name of INSTRUMENT_TABLES) {
    lines.push('', `; ${TABLE_HELP[name]}`, name);
    chunks(Array.from(tables[name].subarray(0, count)), 8).forEach((row, i) => {
      lines.push(`        !byte ${row.map(hex2).join(', ')}    ; ${i * 8}-${i * 8 + row.length - 1}`);
    });
  }
  return lines.join('\n') + '\n';
}

// ---------------------------------------------------------------- song

function label(name) {
  const clean = String(name || 'song').toLowerCase().replace(/[^a-z0-9_]+/g, '_').replace(/^_+|_+$/g, '') || 'song';
  return /^[0-9]/.test(clean) ? 's' + clean : clean;
}

export function exportSongAsm(song, name = song.name) {
  const id = label(name);
  const lines = [
    `; song_${id}.asm - generated by WebSidTracker`,
    versionLine(),
    '; Start it with:  lda #<song_' + id + ' : ldx #>song_' + id + ' : jsr music_init',
    '',
    `song_${id}`,
    `        !byte ${song.speed}                         ; speed: frames per tick`,
    `        !word ${[1, 2, 3].map((v) => `${id}_order_v${v}`).join(', ')}`,
    `        !word ${id}_pattern_table`,
    '',
    `${id}_pattern_table`,
  ];
  song.patterns.forEach((_, i) => lines.push(`        !word ${id}_pat_${i}`));

  song.orders.forEach((entries, v) => {
    lines.push('', `${id}_order_v${v + 1}`);
    entries.forEach((entry, i) => {
      if (entry.stop) lines.push(`        !byte $FE, 0                    ; stop this voice`);
      else if (entry.loop !== undefined) lines.push(`        !byte $FF, ${entry.loop}                    ; loop to entry ${entry.loop}`);
      else lines.push(`        !byte ${entry.pattern}, ${hex2(entry.transpose & 0xFF)}                  ; entry ${i}: pattern ${entry.pattern}, transpose ${signed(entry.transpose)}`);
    });
    const last = entries[entries.length - 1];
    if (!last || !(last.stop || last.loop !== undefined)) {
      lines.push('        !byte $FE, 0                    ; stop this voice (added: the list must not run on)');
    }
  });

  song.patterns.forEach((pattern, i) => {
    lines.push('', `${id}_pat_${i}${pattern.name ? `    ; ${pattern.name}` : ''}`);
    lines.push(...eventLines(pattern.events));
    lines.push('        !byte $FF                       ; end of pattern');
  });
  return lines.join('\n') + '\n';
}

// One assembler line per event of a pattern or an effect.
function eventLines(events) {
  return events.map((ev) => {
    switch (ev.type) {
      case 'note': return `        !byte ${hex2(ev.pitch)}, ${ev.length}                    ; ${noteName(ev.pitch)}, ${ev.length} ticks`;
      case 'rest': return `        !byte $60, ${ev.length}                    ; rest, ${ev.length} ticks`;
      case 'inst': return `        !byte $61, ${ev.instrument}                    ; instrument ${ev.instrument}`;
      case 'legato': return '        !byte $62                       ; legato: next note keeps the envelope';
      default: throw new Error(`unknown event type "${ev.type}"`);
    }
  });
}

// ---------------------------------------------------------------- sound effects

/**
 * The names of the effect constants: SFX_ and the effect's name in capitals ("big boom" -> SFX_BIG_BOOM).
 * An effect without a usable name, or with a name that an earlier one already has, gets its number.
 */
export function effectConstants(effects) {
  const used = new Set();
  return effects.map((effect, n) => {
    const base = String(effect.name || '').toUpperCase().replace(/[^A-Z0-9]+/g, '_').replace(/^_+|_+$/g, '');
    let name = base ? `SFX_${base}` : `SFX_${n}`;
    if (used.has(name)) name = `${name}_${n}`;
    used.add(name);
    return name;
  });
}

export function exportSfxAsm(effects) {
  const names = effectConstants(effects);
  const labels = effects.map((_, n) => `sfx_${n}`);
  const voices = effects.map((effect) => effect.voice);
  const lines = [
    '; sfx.asm - generated by WebSidTracker. Edit the sound effects in the tracker, not here.',
    versionLine(),
    '; Play one with:  lda #SFX_NAME : ldx #voice : jsr sfx_play       (voice 0, 1 or 2; see docs/player.md)',
    '; sfx_voice holds the voice each effect was made for in the tracker; the game may use another one.',
    '',
  ];
  names.forEach((name, n) => lines.push(`${name.padEnd(24)}= ${n}${effects[n].name ? `    ; ${effects[n].name}` : ''}`));
  const table = (label, values) => {
    lines.push('', label);
    if (values.length === 0) lines.push('        ; (no effects)');
    chunks(values, 8).forEach((row) => lines.push(`        !byte ${row.join(', ')}`));
  };
  table('sfx_lo', labels.map((l) => `<${l}`));
  table('sfx_hi', labels.map((l) => `>${l}`));
  table('sfx_voice', voices.map(String));
  lines.push('', 'sfx_count', `        !byte ${effects.length}`);
  effects.forEach((effect, n) => {
    lines.push('', `${labels[n]}${effect.name ? `    ; ${effect.name}` : ''}`);
    lines.push(`        !byte ${effect.speed}                         ; speed: frames per tick`);
    lines.push(...eventLines(effect.events));
    lines.push('        !byte $FF                       ; end of the effect');
  });
  return lines.join('\n') + '\n';
}

// ---------------------------------------------------------------- .prg

// Patches the instrument tables ($2000...), the sound effects ($3100...) and the song ($3800...) into the
// player image. The player image is a PRG: two load-address bytes, then the program. The result is a PRG
// that starts at the same load address and runs to the end of the song. Anything the image had at $2000
// and above (the built-in tables, effects and demo song) is removed first.
export function exportPrg(project, playerPrg) {
  if (!playerPrg || playerPrg.length < 3) throw new Error('player image is empty');
  const load = playerPrg[0] | (playerPrg[1] << 8);
  const playerEnd = load + playerPrg.length - 2;
  if (load >= LIMITS.instrumentBase) throw new Error(`player image loads at $${load.toString(16)}, expected below $2000`);
  if (playerEnd > 0x10000) throw new Error('player image does not fit in 64 KB');

  const problems = validate(project);
  if (problems.length) throw new Error('cannot export: ' + problems.slice(0, 5).join('; '));
  const song = serialiseSong(project.song, LIMITS.songBase);
  if (LIMITS.songBase + song.size > LIMITS.songEnd) {
    throw new Error(`song is ${song.size} bytes, it must end below $${LIMITS.songEnd.toString(16).toUpperCase()} (${LIMITS.songEnd - LIMITS.songBase} bytes available)`);
  }

  const ram = new Uint8Array(0x10000);
  ram.set(playerPrg.subarray(2), load);
  ram.fill(0, LIMITS.instrumentBase); // drop whatever the image had from $2000 up (old tables, demo song)

  const tables = serialiseInstruments(project.instruments);
  INSTRUMENT_TABLES.forEach((name, k) => ram.set(tables[name], LIMITS.instrumentBase + k * 0x100));
  ram.set(serialiseEffects(project.effects ?? [], LIMITS.effectBase).bytes, LIMITS.effectBase);
  ram.set(song.bytes, LIMITS.songBase);

  const end = LIMITS.songBase + song.size;
  const out = new Uint8Array(2 + end - load);
  out[0] = load & 0xFF;
  out[1] = load >> 8;
  out.set(ram.subarray(load, end), 2);
  return out;
}

// ---------------------------------------------------------------- .sid

// A .sid file (PSID version 2) is a header of 124 bytes followed by a piece of C64 memory. A SID
// player program loads the memory, calls the init address once and then the play address once
// per frame. Our player wants the address of the song in A and X when it is started, and a SID
// player cannot give that, so seven bytes of code go in front of the player:
//         lda #<song : ldx #>song : jmp music_init
// The memory in the file is those seven bytes, the player, the instrument tables and the song:
// the same bytes as in the .prg, without the BASIC line and the raster interrupt program (a SID
// player does the timing itself).
export const SID_HEADER_SIZE = 0x7C;
export const SID_TEXT_LENGTH = 32;                  // title, author and released: 32 bytes each
const SID_STUB_SIZE = 7;
const SID_FLAG_PAL = 0x04;                          // bits 2-3: the song is made for a PAL machine
const SID_FLAG_MODEL = { 6581: 0x10, 8580: 0x20, any: 0x30 };   // bits 4-5: the chip it is made for

/**
 * The text fields of the header are 32 bytes of ISO 8859-1 (Latin-1). Characters outside it
 * become "?"; longer text is cut off.
 */
export function sidText(text) {
  const out = new Uint8Array(SID_TEXT_LENGTH);
  const clean = String(text ?? '').replace(/\s+/g, ' ').trim();
  let n = 0;
  for (const char of clean) {
    if (n === SID_TEXT_LENGTH) break;
    const code = char.codePointAt(0);
    out[n++] = (code >= 0x20 && code <= 0x7E) || (code >= 0xA0 && code <= 0xFF) ? code : 0x3F;
  }
  return out;
}

/**
 * The song as a .sid file. `symbols` are the player's addresses (web/player/symbols.json).
 * `info` = { title, author, released, model }: the three text fields (title: the song name when
 * left out; "<?>" is what the SID collections write for unknown) and the chip the song is
 * made for: 6581, 8580 or 'any'.
 */
export function exportSid(project, playerPrg, symbols, info = {}) {
  const init = symbols && symbols.music_init;
  const play = symbols && symbols.music_play;
  const start = symbols && (symbols.music_start ?? symbols.music_init);
  if (![init, play, start].every(Number.isInteger)) throw new Error('the player symbols (music_init, music_play) are missing');
  const prg = exportPrg(project, playerPrg);
  const prgLoad = prg[0] | (prg[1] << 8);
  if (start < prgLoad + SID_STUB_SIZE) throw new Error('the player image has no room for the start code in front of the player');
  const flags = SID_FLAG_MODEL[info.model ?? 'any'];
  if (flags === undefined) throw new Error(`unknown SID model "${info.model}" (use 6581, 8580 or 'any')`);

  const load = start - SID_STUB_SIZE;
  const memory = prg.subarray(2 + start - prgLoad);
  const out = new Uint8Array(SID_HEADER_SIZE + 2 + SID_STUB_SIZE + memory.length);
  const word = (at, value) => { out[at] = value >> 8; out[at + 1] = value & 0xFF; };   // the header is big-endian
  out.set([0x50, 0x53, 0x49, 0x44], 0);             // "PSID"
  word(0x04, 2);                                    // version
  word(0x06, SID_HEADER_SIZE);                      // where the memory starts in the file
  word(0x08, 0);                                    // load address 0: it is the first two bytes of the memory, as in a .prg
  word(0x0A, load);                                 // init
  word(0x0C, play);                                 // play
  word(0x0E, 1);                                    // number of songs
  word(0x10, 1);                                    // the song to start with
  // 0x12: speed, 4 bytes of 0 = play is called once per frame (50 Hz on PAL)
  out.set(sidText(info.title ?? project.song.name), 0x16);
  out.set(sidText(info.author || '<?>'), 0x36);
  out.set(sidText(info.released || '<?>'), 0x56);
  word(0x76, SID_FLAG_PAL | flags);
  // 0x78: no relocation information, no second or third SID: 4 bytes of 0

  let at = SID_HEADER_SIZE;
  out[at++] = load & 0xFF;
  out[at++] = load >> 8;
  out.set([0xA9, LIMITS.songBase & 0xFF, 0xA2, LIMITS.songBase >> 8, 0x4C, init & 0xFF, init >> 8], at);
  out.set(memory, at + SID_STUB_SIZE);
  return out;
}

// ---------------------------------------------------------------- project file

const PROJECT_FORMAT_NAME = 'websidtracker-project';

export function projectToJson(project) {
  return JSON.stringify({
    format: PROJECT_FORMAT_NAME, version: FORMAT, release: RELEASE,
    instruments: project.instruments, song: project.song, effects: project.effects ?? [],
  }, null, 1);
}

/**
 * Throws when the data does not have the two parts every project file has, in any format. It runs before
 * the format is looked at, so some other JSON file is called "not a project file" and not "an older project".
 */
export function checkProjectShape(data) {
  if (!data || typeof data !== 'object' || !Array.isArray(data.instruments) || !data.song || typeof data.song !== 'object') {
    throw new Error('This is not a project file (instruments or song missing).');
  }
}

/** Defaults and checks for project data of the current format (no version check). */
export function projectFromData(data) {
  checkProjectShape(data);
  const song = {
    name: 'untitled', speed: 6, patterns: [], orders: [[], [], []], ...data.song,
  };
  const instruments = data.instruments.map((inst) => (inst && typeof inst === 'object' ? { ...defaultInstrument(), ...inst } : null));
  // A format 2 file written before the sound effects existed has no effects (and no slide: see defaultInstrument).
  const effects = Array.isArray(data.effects) ? data.effects : [];
  const project = { instruments, song, effects };
  const problems = validate(project);
  if (problems.length) {
    const more = problems.length > 8 ? ` (and ${problems.length - 8} more)` : '';
    throw new Error('The project file has problems: ' + problems.slice(0, 8).join('; ') + more);
  }
  return project;
}

export function parseProjectText(text) {
  try {
    return JSON.parse(text);
  } catch (e) {
    throw new Error('This is not a project file (not valid JSON).');
  }
}

/** Opens a project file of exactly the current format. Other formats: see inspectProject in migrate.js. */
export function projectFromJson(text) {
  const data = parseProjectText(text);
  const format = readFormat(data);
  if (format > FORMAT) throw new NewerFormatError(format, typeof data.release === 'string' ? data.release : null);
  checkProjectShape(data);
  if (format < FORMAT) throw new OlderFormatError(format);
  return projectFromData(data);
}
