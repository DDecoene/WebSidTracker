// export.js - assembler text (ACME syntax), the ready-to-run .prg, and the project file (JSON).
//
// The assembler text has exactly the layout of serialise.js, so a song file assembled
// at some address gives the same bytes as serialiseSong(song, thatAddress).
//
// Part of the WebSidTracker web app, GPL version 3 or later (see ../LICENSE).

import { INSTRUMENT_TABLES, serialiseInstruments, serialiseSong } from './serialise.js';
import { LIMITS, defaultInstrument, noteName, validate } from './project.js';

const hex2 = (v) => '$' + v.toString(16).toUpperCase().padStart(2, '0');
const signed = (v) => (v < 0 ? String(v) : '+' + v);

// Chunks an array into lines of `size` values.
function chunks(values, size) {
  const out = [];
  for (let i = 0; i < values.length; i += size) out.push(values.slice(i, i + size));
  return out;
}

// ---------------------------------------------------------------- instruments

const TABLE_HELP = {
  inst_wave: 'control register without the gate bit (waveform in bits 7-4)',
  inst_ad: 'attack / decay',
  inst_sr: 'sustain / release',
  inst_pw_lo: 'start pulse width, low byte',
  inst_pw_hi: 'start pulse width, high nibble',
  inst_pw_step: 'pulse sweep per frame (signed)',
  inst_pw_min: 'sweep lower limit, pulse width / 16',
  inst_pw_max: 'sweep upper limit, pulse width / 16',
  inst_vib_delay: 'frames before the vibrato starts',
  inst_vib_depth: 'vibrato width, 1/16 of the distance to the next semitone',
  inst_vib_speed: 'frames per half vibrato period',
  inst_arp: 'arpeggio offset in semitones (signed)',
  inst_drum_noise: 'drum: frames of noise at the start (0 = not a drum)',
  inst_drum_fall: 'drum: frequency units the tone falls per frame',
  inst_release: 'frames at the end of a note kept for the clean restart',
};

// Number of table entries to export: highest defined instrument + 1 (at least 1).
function usedInstruments(instruments) {
  return Math.max(1, instruments.reduce((top, inst, n) => (inst ? n + 1 : top), 0));
}

export function exportInstrumentsAsm(instruments) {
  const count = usedInstruments(instruments);
  const tables = serialiseInstruments(instruments);
  const lines = [
    '; instruments.asm - generated by WebSidTracker. Edit the instruments in the tracker, not here.',
    '; One table per field, indexed by the instrument number (see docs/design-player-format-and-timing.md, section 5).',
    ';',
    '; Instruments in this file:',
  ];
  for (let n = 0; n < count; n++) lines.push(`;   ${hex2(n)}  ${instruments[n] ? instruments[n].name : '(unused)'}`);
  for (const name of INSTRUMENT_TABLES) {
    lines.push('', `; ${TABLE_HELP[name]}`, name);
    chunks(Array.from(tables[name].subarray(0, count)), 8).forEach((row, i) => {
      lines.push(`        !byte ${row.map(hex2).join(', ')}    ; ${i * 8}-${i * 8 + row.length - 1}`);
    });
  }
  return lines.join('\n') + '\n';
}

// ---------------------------------------------------------------- song

function label(name) {
  const clean = String(name || 'song').toLowerCase().replace(/[^a-z0-9_]+/g, '_').replace(/^_+|_+$/g, '') || 'song';
  return /^[0-9]/.test(clean) ? 's' + clean : clean;
}

export function exportSongAsm(song, name = song.name) {
  const id = label(name);
  const lines = [
    `; song_${id}.asm - generated by WebSidTracker`,
    '; Start it with:  lda #<song_' + id + ' : ldx #>song_' + id + ' : jsr music_init',
    '',
    `song_${id}`,
    `        !byte ${song.speed}                         ; speed: frames per tick`,
    `        !word ${[1, 2, 3].map((v) => `${id}_order_v${v}`).join(', ')}`,
    `        !word ${id}_pattern_table`,
    '',
    `${id}_pattern_table`,
  ];
  song.patterns.forEach((_, i) => lines.push(`        !word ${id}_pat_${i}`));

  song.orders.forEach((entries, v) => {
    lines.push('', `${id}_order_v${v + 1}`);
    entries.forEach((entry, i) => {
      if (entry.stop) lines.push(`        !byte $FE, 0                    ; stop this voice`);
      else if (entry.loop !== undefined) lines.push(`        !byte $FF, ${entry.loop}                    ; loop to entry ${entry.loop}`);
      else lines.push(`        !byte ${entry.pattern}, ${hex2(entry.transpose & 0xFF)}                  ; entry ${i}: pattern ${entry.pattern}, transpose ${signed(entry.transpose)}`);
    });
    const last = entries[entries.length - 1];
    if (!last || !(last.stop || last.loop !== undefined)) {
      lines.push('        !byte $FE, 0                    ; stop this voice (added: the list must not run on)');
    }
  });

  song.patterns.forEach((pattern, i) => {
    lines.push('', `${id}_pat_${i}${pattern.name ? `    ; ${pattern.name}` : ''}`);
    for (const ev of pattern.events) {
      switch (ev.type) {
        case 'note': lines.push(`        !byte ${hex2(ev.pitch)}, ${ev.length}                    ; ${noteName(ev.pitch)}, ${ev.length} ticks`); break;
        case 'rest': lines.push(`        !byte $60, ${ev.length}                    ; rest, ${ev.length} ticks`); break;
        case 'inst': lines.push(`        !byte $61, ${ev.instrument}                    ; instrument ${ev.instrument}`); break;
        case 'legato': lines.push('        !byte $62                       ; legato: next note keeps the envelope'); break;
        default: throw new Error(`unknown event type "${ev.type}"`);
      }
    }
    lines.push('        !byte $FF                       ; end of pattern');
  });
  return lines.join('\n') + '\n';
}

// ---------------------------------------------------------------- .prg

const TABLE_END = LIMITS.instrumentBase + INSTRUMENT_TABLES.length * 0x100; // $2F00

// Patches the instrument tables ($2000...) and the song ($3000...) into the player image.
// The player image is a PRG: two load-address bytes, then the program. The result is a PRG
// that starts at the same load address and runs to the end of the song. Anything the image
// had at $3000 and above (the built-in demo song) is removed first.
export function exportPrg(project, playerPrg) {
  if (!playerPrg || playerPrg.length < 3) throw new Error('player image is empty');
  const load = playerPrg[0] | (playerPrg[1] << 8);
  const playerEnd = load + playerPrg.length - 2;
  if (load >= LIMITS.instrumentBase) throw new Error(`player image loads at $${load.toString(16)}, expected below $2000`);
  if (playerEnd > 0x10000) throw new Error('player image does not fit in 64 KB');

  const problems = validate(project);
  if (problems.length) throw new Error('cannot export: ' + problems.slice(0, 5).join('; '));
  const song = serialiseSong(project.song, LIMITS.songBase);
  if (LIMITS.songBase + song.size > LIMITS.songEnd) {
    throw new Error(`song is ${song.size} bytes, it must end below $${LIMITS.songEnd.toString(16).toUpperCase()} (${LIMITS.songEnd - LIMITS.songBase} bytes available)`);
  }

  const ram = new Uint8Array(0x10000);
  ram.set(playerPrg.subarray(2), load);
  ram.fill(0, LIMITS.instrumentBase); // drop whatever the image had from $2000 up (old tables, demo song)

  const tables = serialiseInstruments(project.instruments);
  INSTRUMENT_TABLES.forEach((name, k) => ram.set(tables[name], LIMITS.instrumentBase + k * 0x100));
  ram.set(song.bytes, LIMITS.songBase);

  const end = Math.max(TABLE_END, LIMITS.songBase + song.size, Math.min(playerEnd, LIMITS.instrumentBase));
  const out = new Uint8Array(2 + end - load);
  out[0] = load & 0xFF;
  out[1] = load >> 8;
  out.set(ram.subarray(load, end), 2);
  return out;
}

// ---------------------------------------------------------------- project file

const FORMAT = 'websidtracker-project';

export function projectToJson(project) {
  return JSON.stringify({ format: FORMAT, version: 1, instruments: project.instruments, song: project.song }, null, 1);
}

export function projectFromJson(text) {
  let data;
  try {
    data = JSON.parse(text);
  } catch (e) {
    throw new Error('This is not a project file (not valid JSON).');
  }
  if (!data || typeof data !== 'object' || !Array.isArray(data.instruments) || !data.song || typeof data.song !== 'object') {
    throw new Error('This is not a project file (instruments or song missing).');
  }
  const song = {
    name: 'untitled', speed: 6, patterns: [], orders: [[], [], []], ...data.song,
  };
  const instruments = data.instruments.map((inst) => (inst && typeof inst === 'object' ? { ...defaultInstrument(), ...inst } : null));
  const project = { instruments, song };
  const problems = validate(project);
  if (problems.length) {
    const more = problems.length > 8 ? ` (and ${problems.length - 8} more)` : '';
    throw new Error('The project file has problems: ' + problems.slice(0, 8).join('; ') + more);
  }
  return project;
}
